-- 공개 사용자 이름(@아이디)을 users에 더한다.
--
-- 친구 찾기를 가입 이메일 정확 일치에서 공개 사용자 이름으로 옮기기 위한
-- 저장 계층 변경이다. 이메일로 친구를 찾을 수 있으면 요청 성공/실패가 곧
-- "이 주소로 가입했는가"에 대한 답이 되어, 친구 기능이 이메일 열거 수단이 된다.
--
-- ## NOT NULL로 만들지 않는 이유
--
-- 이 마이그레이션이 도는 시점에 이미 계정을 가진 사람들이 있고, 그들의 이름은
-- 본인만 정할 수 있다. 서버가 대신 짓는 순간 재료가 될 만한 값(이메일 앞부분,
-- 별칭, 부대, 계급)은 전부 비공개 정보이고, 그것을 공개 식별자로 만드는 것은
-- 이 서비스가 지금까지 지켜 온 최소 수집 원칙을 정면으로 어긴다. 무작위 문자열을
-- 넣는 것도 답이 아니다 — 아무도 기억하지 못하는 공개 이름이 남고, 나중에 진짜
-- 이름을 정할 때 "이미 있는 값"을 비켜 가야 한다.
--
-- 그래서 저장 계층은 NULL을 허용하고, "활성 사용자에게는 이름이 있다"는 불변식은
-- 애플리케이션 경계가 지킨다.
--   1) 신규 가입: 온보딩의 username 단계에서 정하며, 이름이 없으면
--      `POST /auth/onboarding/complete`가 완료를 거부한다.
--   2) 기존 계정: 다음 인증 세션에서 1회성 설정 화면이 뜬다(웹·앱 공통).
--      이름이 생기기 전까지 친구 찾기·프로필 공유만 잠기고 나머지는 그대로 쓴다.
--
-- ## 유일성을 인덱스로 거는 이유
--
-- "있는지 조회하고 없으면 넣는다"는 동시 요청 두 건 사이에서 반드시 깨진다.
-- 같은 이름을 노린 두 요청이 둘 다 조회를 통과한 뒤 둘 다 INSERT 한다.
-- 유니크 인덱스가 있으면 둘 중 하나가 SQLITE_CONSTRAINT로 떨어지고, 라우트가
-- 그것을 409로 바꾼다(routes/users.ts의 claimUsername).
--
-- 저장되는 값은 언제나 정규형이다(@leave/shared의 normalizeUsername: trim → NFC
-- → 영문 소문자). 그래서 BINARY 비교만으로 `HyunWoo`와 `hyunwoo`가 같은 이름이
-- 되고, 분해형으로 적은 한글이 완성형과 다른 계정이 되지 못한다.
-- SQLite에서 NULL끼리는 서로 다르므로 이름 없는 옛 계정은 이 인덱스에서 충돌하지 않는다.
--
-- 이 인덱스 하나가 검색까지 맡는다 — 사용자 검색은
-- `username >= :prefix AND username < :prefixUpperBound ORDER BY username LIMIT 20`
-- 이라, 인덱스 정렬 순서를 그대로 타고(TEMP B-TREE 없음) 정확히 일치하는 이름이
-- 접두어들보다 항상 먼저 나온다. LIKE를 쓰지 않는 이유는 `_`가 이름에 쓸 수 있는
-- 문자라서다 — LIKE 패턴에서 `_`는 와일드카드이고, ESCAPE를 붙이면 SQLite의
-- LIKE 최적화가 꺼져 인덱스를 못 쓴다.
